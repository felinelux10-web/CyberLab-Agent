"""
Mode Detector — Series 10-A
يصنف نوع الرسالة قبل أي معالجة.
"""

TASK_PATTERNS = [
    "افحص","اقرأ","اكتب","حلل","شغّل","شغل","نفذ","احذف",
    "انشئ","أنشئ","عدل","اعرض","ابحث","افهم","استرجع",
    "احفظ الجلسة","خريطة","تاثير","اعتماديات","خطورة",
]

SYSTEM_PATTERNS = [
    "استكمل الجلسة","احفظ الجلسة","امسح الحوار",
    "أعد التشغيل","اعد التشغيل","اعرض آخر جلسة",
    "ما اخر جلسة","ما آخر جلسة","حالة النظام",
]

DISCUSSION_PATTERNS = [
    "دعنا نناقش","ما الأفضل","ما رأيك في","نناقش",
    "ما الفرق بين","أيهما أفضل","ما الخيار",
    "تكلم معي عن","حدثني عن","حدثني حول",
    "أخبرني عن","ناقش معي","خلينا نتكلم عن",
    "لنتحدث عن","اريد ان اتكلم عن","أريد أن أتكلم عن",
]

QUESTION_PATTERNS = [
    "اشرح لي","اشرح","ما هو","ما هي","ما وظيفة","ما وظيفته",
    "ما وظيفتها","ما دور","ما دوره","ما دورها","كيف يعمل",
    "كيف تعمل","عرفني على",
    "ماذا تعرف عن",
    "ما رأيك","هل تعتقد","هل تظن","ما اقتراحك",
    "ماذا تقترح","كيف ترى","ما وجهة نظرك",

    # أسئلة التعارف
    "من أنت","من انت","ما اسمك","عرف بنفسك",
    "ماذا تستطيع","ماذا يمكنك","ما وظيفتك",
    "ما الذي تستطيع فعله","من تكون",

    # اقتراحات عامة
    "ما الذي تقترحه",
    "بماذا تنصح",
    "ما الذي تنصح",
    "اقترح علي",
    "اقترح لي",
]

FOLLOW_UP_PATTERNS = [
    "هذا","هذه","ذلك","تلك","نفسه","نفسها",
    "السابق","السابقة","الملف السابق","الحل الثاني",
    "نفس الملف","نفس الأمر","اكمل","أكمل","تابع",

    # متابعة الحوار
    "ولماذا",
    "لماذا",
    "وما علاقته",
    "ما علاقته",
    "وماذا",
    "ماذا عن",
    "هل تنصحني",
    "تنصحني",
    "ما دوره",
    "كيف يعمل",
    "ما علاقة",
    "علاقته",
    "ثم",
    "لخصهما",
    "ما دوره",
    "كيف يعمل",
    "كيف يعمل هذا",
    "ما علاقته",
    "ما علاقته بالمشروع",
    "لخصه",
    "لخصها",
]

CHAT_PATTERNS = [
    "شكراً","شكرا","مرحبا","مرحباً","كيف حالك",
    "أهلاً","اهلا","صباح","مساء","وداعاً",
]


def detect_mode(text: str) -> str:
    """
    يعيد: TASK / SYSTEM / DISCUSSION / QUESTION / FOLLOW_UP / CHAT.

    FOLLOW_UP له أولوية على QUESTION عندما تكون الرسالة متابعة قصيرة
    واضحة، بينما DISCUSSION يحتفظ بأولوية أعلى عندما تكون صيغة الرأي/النقاش صريحة.
    """
    t = text.strip()

    if not t:
        return "CHAT"

    # SYSTEM — أوامر الوكيل نفسه.
    if any(p in t for p in SYSTEM_PATTERNS):
        return "SYSTEM"

    # TASK — الأوامر التنفيذية الصريحة لها الأولوية.
    if any(p in t for p in TASK_PATTERNS):
        return "TASK"

    # FOLLOW_UP — المتابعات القصيرة الواضحة يجب أن تسبق QUESTION.
    stripped = t

    exact_followups = {
        "كيف يعمل؟", "كيف يعمل",
        "لماذا؟", "لماذا",
        "ما دوره؟", "ما دوره",
        "ما وظيفته؟", "ما وظيفته",
        "ما علاقته؟", "ما علاقته",
        "ماذا عنه؟", "ماذا عنه",
        "ماذا عن ذلك؟", "ماذا عن ذلك",
        "ماذا عن هذا؟", "ماذا عن هذا",
        "ماذا عن السابق؟", "ماذا عن السابق",
        "ما التالي؟", "ما التالي",
        "ثم ماذا؟", "ثم ماذا",
        "وماذا بعد؟", "وماذا بعد",
        "لخصه", "لخصها", "لخصهما",
        "أكمل", "اكمل", "تابع",
    }

    if stripped in exact_followups:
        return "FOLLOW_UP"

    reference_prefixes = (
        "ولماذا",
        "وما علاقته",
        "وماذا عن",
        "وأيهما",
    )

    if any(stripped.startswith(p) for p in reference_prefixes):
        return "FOLLOW_UP"

    # صيغ مرجعية صريحة من نوع:
    # "ماذا عن هذا التصميم؟"
    # "ما علاقته بهذا؟"
    #
    # لا نعتمد على وجود "هذا" وحدها؛ يجب أن تكون الصيغة
    # واحدة من البنى المرجعية المعروفة.
    if stripped.startswith("ماذا عن "):
        return "FOLLOW_UP"

    if stripped.startswith("ما علاقته "):
        return "FOLLOW_UP"

    if stripped.startswith("وما علاقته "):
        return "FOLLOW_UP"

    # DISCUSSION — الرأي والمقارنة والنقاش الصريح.
    if any(p in t for p in DISCUSSION_PATTERNS):
        return "DISCUSSION"

    # QUESTION — الأسئلة الكاملة العامة.
    if any(p in t for p in QUESTION_PATTERNS):
        return "QUESTION"

    # CHAT — التحية والمحادثة الاجتماعية البسيطة.
    if any(p in t for p in CHAT_PATTERNS):
        return "CHAT"

    # أسئلة عامة شائعة.
    if any(
        p in t
        for p in (
            "ماذا لدينا",
            "ماذا يوجد",
            "ما لدينا",
            "ما الموجود",
            "كيف حالك",
            "كيف الحال",
        )
    ):
        return "QUESTION"

    # المحافظة على السلوك القديم كـ TASK افتراضي.
    return "TASK"
